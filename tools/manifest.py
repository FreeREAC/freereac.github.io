#!/usr/bin/env python3
"""The import manifest, generated from and verified against the OpenMixer channel's own indexes.

  manifest.py generate --base URL|DIR [--fedora 45] [--arch x86_64 aarch64 noarch SRPMS] [--suite bookworm trixie]   manifest on stdout
  manifest.py verify   --base URL|DIR MANIFEST [--head]                          every line resolves in the live index

generate reads the dnf repository of each Fedora release and architecture (repodata/repomd.xml, then the primary index) and the
flat apt index of each suite (deb/debian/<suite>/Packages), keeps the packages of FreeREAC (libreac, reac-pw, reac-stageboxes and
their subpackages), and writes the newest 2 versions of each package in each tree, with the sha256 the index states.

verify refuses, naming the line, a manifest line the index does not list at that directory with that sha256 (a stale manifest: the
channel pruned or moved the file), and with --head one the server does not answer 200 for. The PR check runs it, so a stale manifest
is refused in the pull request and not when the import runs.

Exit 0 ok, 1 a manifest line is not served, 2 the index could not be read.
"""
import argparse
import gzip
import lzma
import re
import subprocess
import sys
import urllib.request
import xml.etree.ElementTree as ET

RPM_NAMES = re.compile(r"^(libreac|libreac-devel|libreac-tests|libreac-transport|libreac-transport-devel|reac-pw|reac-pw-devel|reac-stageboxes)$")
DEB_NAMES = re.compile(r"^(libreac\d*|libreac-dev|libreac-tests|libreac-transport\d*|libreac-transport-dev|reac-pw|reac-pw-dev|reac-stageboxes)$")
NS = {"c": "http://linux.duke.edu/metadata/common", "r": "http://linux.duke.edu/metadata/repo"}
HEADER = """# FreeREAC channel import manifest. One line per file:  <rpm|deb> <directory in the OpenMixer channel> <file> <sha256>
# Read by .github/workflows/import.yml when a reviewed PR that changes this file merges. Each file is fetched from
# https://www.openmixer.org, its sha256 and its current signature checked, and it joins the FreeREAC channel (docs/design.md).
# The channel keeps the newest 2 versions of each package in each tree: this list holds at most 2 per package per tree.
# Generated by tools/manifest.py generate from the OpenMixer channel's own indexes and checked against them by tools/manifest.py
# verify on every pull request: libreac, reac-pw, reac-stageboxes (and their -devel/-tests/-transport subpackages),
# fedora 45, every architecture published and SRPMS, deb bookworm + trixie. mod-host is not listed (docs/design.md).
"""


class Cannot(Exception):
    pass


def read(src):
    try:
        if re.match(r"^https?://", src):
            req = urllib.request.Request(src, headers={"User-Agent": "freereac-manifest"})
            with urllib.request.urlopen(req, timeout=60) as r:
                data = r.read()
        else:
            with open(src, "rb") as f:
                data = f.read()
    except Exception as e:  # noqa: BLE001
        raise Cannot(f"{src} could not be read: {e}") from e
    if src.endswith(".gz"):
        data = gzip.decompress(data)
    elif src.endswith(".xz"):
        data = lzma.decompress(data)
    elif src.endswith(".zst"):
        data = subprocess.run(["zstd", "-dc"], input=data, capture_output=True, check=True).stdout
    return data


def exists(src):
    if not re.match(r"^https?://", src):
        return True
    try:
        req = urllib.request.Request(src, method="HEAD", headers={"User-Agent": "freereac-manifest"})
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.status == 200
    except Exception:  # noqa: BLE001
        return False


def vkey(v):
    return [int(x) if x.isdigit() else x for x in re.split(r"[.\-~+]", v)]


def rpm_index(base, rel, arch):
    """{(name, file): (version-release, sha256)} of the dnf repository fedora/<rel>/<arch>, or None when it serves none."""
    root = f"{base.rstrip('/')}/rpm/fedora/{rel}/{arch}"
    try:
        repomd = ET.fromstring(read(f"{root}/repodata/repomd.xml"))
    except Cannot:
        return None
    href = next((d.find("r:location", NS).get("href") for d in repomd.findall("r:data", NS) if d.get("type") == "primary"), None)
    if not href:
        raise Cannot(f"{root}/repodata/repomd.xml names no primary index")
    out = {}
    for p in ET.fromstring(read(f"{root}/{href}")).findall("c:package", NS):
        name = p.find("c:name", NS).text
        v = p.find("c:version", NS)
        sha = p.find("c:checksum", NS)
        if sha.get("type") != "sha256":
            raise Cannot(f"{root}: {name} has a {sha.get('type')} checksum, sha256 is needed")
        out[(name, p.find("c:location", NS).get("href").rsplit("/", 1)[-1])] = (f"{v.get('ver')}-{v.get('rel')}", sha.text)
    return out


def deb_index(base, suite):
    """{(package, file): (version, sha256, directory)} of the flat index deb/debian/<suite>/Packages."""
    root = f"{base.rstrip('/')}/deb/debian/{suite}"
    out = {}
    for stanza in read(f"{root}/Packages").decode().split("\n\n"):
        f = dict(re.findall(r"^([A-Za-z0-9-]+): (.*)$", stanza, re.M))
        if "Package" not in f:
            continue
        fn = f["Filename"].lstrip("./")
        d, _, name = fn.rpartition("/")
        out[(f["Package"], name)] = (f["Version"], f["SHA256"], f"deb/debian/{suite}" + (f"/{d}" if d else ""))
    return out


def generate(a):
    rows = []
    for rel in a.fedora:
        for arch in a.arch:
            idx = rpm_index(a.base, rel, arch)
            if idx is None:
                continue
            by = {}
            for (name, file), (ver, sha) in idx.items():
                if RPM_NAMES.match(name):
                    by.setdefault(name, []).append((ver, file, sha))
            for name, vs in by.items():
                for ver in sorted({v for v, _, _ in vs}, key=vkey)[-2:]:
                    rows += [("rpm", f"rpm/fedora/{rel}/{arch}", file, sha) for v, file, sha in vs if v == ver]
    for suite in a.suite:
        by = {}
        for (name, file), (ver, sha, d) in deb_index(a.base, suite).items():
            if DEB_NAMES.match(name):
                by.setdefault((d, name), []).append((ver, file, sha))
        for (d, name), vs in by.items():
            for ver in sorted({v for v, _, _ in vs}, key=vkey)[-2:]:
                rows += [("deb", d, file, sha) for v, file, sha in vs if v == ver]
    if not rows:
        raise Cannot("the index lists no FreeREAC package")
    sys.stdout.write(HEADER + "".join(" ".join(r) + "\n" for r in sorted(rows)))
    return 0


def verify(a):
    lines = [l.split() for l in open(a.manifest) if l.strip() and not l.startswith("#")]
    rpm_cache, deb_cache, bad = {}, {}, []
    for kind, d, file, sha in lines:
        if kind == "rpm":
            m = re.match(r"^rpm/fedora/(\d+)/([^/]+)$", d)
            if not m:
                bad.append(f"{d}/{file}: not an rpm/fedora/<release>/<arch> directory")
                continue
            idx = rpm_cache.setdefault(m.groups(), rpm_index(a.base, *m.groups()))
            hit = next(((v, s) for (n, f), (v, s) in (idx or {}).items() if f == file), None)
        elif kind == "deb":
            m = re.match(r"^deb/debian/([^/]+)/", d + "/")
            if not m:
                bad.append(f"{d}/{file}: not a deb/debian/<suite>/<arch> directory")
                continue
            idx = deb_cache.setdefault(m.group(1), deb_index(a.base, m.group(1)))
            hit = next(((v, s) for (n, f), (v, s, dd) in idx.items() if f == file and dd == d), None)
        else:
            bad.append(f"{d}/{file}: kind '{kind}' is neither rpm nor deb")
            continue
        if hit is None:
            bad.append(f"{d}/{file}: the channel's index does not list it there (pruned or moved since the manifest was written)")
        elif hit[1] != sha:
            bad.append(f"{d}/{file}: the index states sha256 {hit[1]}, the manifest {sha}")
        elif a.head and not exists(f"{a.base.rstrip('/')}/{d}/{file}"):
            bad.append(f"{d}/{file}: the server does not answer 200")
    for b in bad:
        print(f"FAIL: {b}", file=sys.stderr)
    print(f"manifest: {len(lines)} lines, {len(bad)} not served")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--base", required=True)
    g.add_argument("--fedora", nargs="+", default=["45"])
    g.add_argument("--arch", nargs="+", default=["x86_64", "aarch64", "noarch", "SRPMS"])
    g.add_argument("--suite", nargs="+", default=["bookworm", "trixie"])
    v = sub.add_parser("verify")
    v.add_argument("--base", required=True)
    v.add_argument("--head", action="store_true")
    v.add_argument("manifest")
    a = ap.parse_args()
    try:
        return generate(a) if a.cmd == "generate" else verify(a)
    except Cannot as e:
        print(f"CANNOT: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
